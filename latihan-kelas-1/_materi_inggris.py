from _alat import *

def _warna(c, nama):
    return svg(f'<circle cx="120" cy="62" r="46" fill="{c}" stroke="{INK}" stroke-width="4"/>'
               f'<text x="120" y="136" text-anchor="middle" font-size="26" font-weight="800" fill="{INK}" font-family="sans-serif">{nama}</text>', 240, 150)

def _deret(daftar):
    """Deret angka besar + kata Inggris, mis. [(1,'one'),...]."""
    n = len(daftar); w = 60 * n + 20
    body = ''
    for i, (a, k) in enumerate(daftar):
        x = 40 + i * 60
        body += (f'<circle cx="{x}" cy="40" r="24" fill="#F5B82E" stroke="{INK}" stroke-width="4"/>'
                 f'<text x="{x}" y="49" text-anchor="middle" font-size="26" font-weight="800" fill="{INK}" font-family="sans-serif">{a}</text>'
                 f'<text x="{x}" y="92" text-anchor="middle" font-size="15" font-weight="800" fill="{INK}" font-family="sans-serif">{k}</text>')
    return svg(body, w, 110)

